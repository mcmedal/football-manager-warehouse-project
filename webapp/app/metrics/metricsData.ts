/**
 * Lookup helper: finds a MetricDefinition by field key, id, or alias
 */
export function findMetric(query: string): MetricDefinition | undefined {
  if (!query) return undefined;
  const q = query.toLowerCase().trim();
  return METRIC_DEFINITIONS.find(
    (m) =>
      m.id.toLowerCase() === q ||
      m.fieldKey.toLowerCase() === q ||
      m.aliases.some((a) => a.toLowerCase() === q) ||
      m.code.toLowerCase() === q ||
      m.name.toLowerCase() === q
  );
}
